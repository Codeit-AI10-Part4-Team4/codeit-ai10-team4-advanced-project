"""문구 품질 지표 — 순수 함수. 외부 의존성 없음 (eval/README 규칙).

**무엇을 재는가.** 지금까지 문구 쪽 테스트 27개는 전부 *프롬프트에 지시가 들어갔는가*
를 본다(`test_지어내지_말라고_지시한다` 등). 대역(FakeClient)이 우리가 시킨 답을
돌려주므로 **모델이 그 지시를 실제로 지키는지는 구조적으로 확인할 수 없다.**
여기는 반대로 **나온 문구만** 보고 잰다. 프롬프트를 안 본다.

## 왜 이 두 축인가

`AGENTS.md` 의 규칙 — *"광고의 사실 주장은 사장님이 말한 것에 근거한다.
재료·품질·맛·수상·인증·원산지·인기처럼 확인할 수 없는 특징은 업종 통념으로
추론하지 않는다 — 사실과 다른 광고가 된다."*

지키지 못하면 **사실과 다른 광고**가 나간다. 포스터 쪽은 #23 에서 한 번 손봤지만
문구 쪽은 프롬프트에 한 줄 적어둔 것이 전부고, 지켜지는지 잰 적이 없다.

| 축 | 성격 |
|---|---|
| `price_violations` | **결정적.** 금액은 숫자라 해석의 여지가 없다 |
| `ungrounded_claims` | **계기판.** 낱말 맞추기라 완벽하지 않다 |

## 계기판은 놓치는 쪽으로 기울인다

`panel_metrics.price_contradictions` 가 첫 판에 5건을 잡고 **5건 다 오탐**이었던
전례를 따른다. 잘못 울리는 계기판은 안 울리는 것보다 나쁘다 — 오탐이 쌓이면
결국 아무도 안 본다. 그래서

- 낱말은 **주장이 분명한 것만** 넣는다. `"맛있는"`·`"좋은"` 같은 상투어는 뺐다.
  광고 문구에서 이것들은 사실 주장이라기보다 인사말에 가깝고, 넣으면 거의 모든
  문구가 걸려 신호가 죽는다.
- 사장님이 그 말을 했으면 **근거 있는 것으로 본다** (`grounds` 대조).

**판정이 아니라 계기판이다.** 걸린 것을 눈으로 확인하고 판단하라.
"""

from __future__ import annotations

import re

#: 금액. `4,500원` · `1만원` · `5천원` · `1만 5천원` · `2만 3천 500원` 을 잡는다.
#:
#: 만·천·나머지를 **한 덩어리로** 읽는다. 전에는 `(\d[\d,]*)\s*(만원|천원|원)` 이라
#: `"1만 5천원"` 에서 앞의 `1만` 을 통째로 놓치고 `{5000}` 만 냈다. 주석에는
#: "10,000 과 5,000 두 개로 읽힌다" 고 적혀 있었지만 사실이 아니었고, 그래서
#: "어차피 없는 금액 신호가 뜬다" 는 안전 논리도 성립하지 않았다 — 주문서가
#: 5,000원이면 문구에 `"1만 5천원"` 이 적혀도 위반 없이 통과했다.
#:
#: 세 자리가 전부 선택이라 `"원두"` 의 `원` 처럼 숫자 없는 곳에도 빈 매치가 걸린다.
#: 그건 `amounts()` 에서 걸러낸다.
_AMOUNT = re.compile(
    r"(?:(\d[\d,]*)\s*만)?\s*"  # 만 단위
    r"(?:(\d[\d,]*)\s*천)?\s*"  # 천 단위
    r"(\d[\d,]*)?\s*원"  # 나머지 (또는 `4,500원` 처럼 단위 없는 금액)
)

#: 근거 없이 쓰면 사실과 다른 광고가 되는 낱말. AGENTS.md 의 분류를 따랐다.
#: 사장님이 직접 말했으면 근거가 있는 것이므로 걸리지 않는다(`grounds` 대조).
CLAIM_TERMS: dict[str, tuple[str, ...]] = {
    "품질·등급": ("최고", "최상", "최고급", "최상급", "1위", "일등", "명품", "프리미엄", "특급"),
    "재료": ("국산", "유기농", "무농약", "친환경", "천연", "수제", "엄선", "신선한"),
    "원산지·전통": ("원조", "정통", "본고장", "전통있는"),
    "인기": ("소문난", "줄서는", "인기폭발", "화제의", "유명한"),
    "수상·인증": ("수상", "인증", "공인", "선정된"),
}


def _digits(part: str) -> int:
    return int(part.replace(",", "")) if part else 0


def amounts(text: str) -> set[int]:
    """문구에 적힌 금액을 원 단위 정수로 뽑는다.

    `"1만 5천원"` 처럼 단위가 겹친 금액은 **하나로 더해서** 15,000 을 낸다.
    쪼개서 두 개로 내면 주문서 금액과 우연히 맞아떨어져 위반을 놓친다.
    """
    found = set()
    for man, cheon, rest in _AMOUNT.findall(text):
        if not (man or cheon or rest):
            continue  # 숫자 없이 `원` 만 있는 자리 (`원두` 등)
        found.add(_digits(man) * 10_000 + _digits(cheon) * 1_000 + _digits(rest))
    return found


def price_violations(text: str, *, show_price: bool, price: int) -> list[str]:
    """가격 규칙을 어긴 것. 없으면 빈 목록.

    두 가지를 본다 —
      1. 가격을 **넣지 말라**고 했는데 넣었다 (`show_price=False`)
      2. 주문서와 **다른 금액**을 썼다

    둘 다 표시광고법에 걸리는 종류다. 사장님이 말한 적 없는 금액이 광고에
    적히면 그건 우리가 지어낸 가격이다.
    """
    found = amounts(text)
    if not show_price:
        return [f"가격을 빼라고 했는데 {value:,}원이 적혔다" for value in sorted(found)]
    return [f"주문서는 {price:,}원인데 문구엔 {value:,}원" for value in sorted(found - {price})]


def ungrounded_claims(text: str, grounds: str) -> list[tuple[str, str]]:
    """근거 없는 사실 주장. `(갈래, 낱말)` 목록.

    `grounds` 는 **모델에게 사실로 준 것 전부**를 이어 붙인 문자열이다
    (상품·이유·느낌·요청·사장님 말 원문·사진 메모). 거기 있는 말을 문구가
    다시 쓴 것은 지어낸 것이 아니다.

    사진 메모를 근거에 넣는 이유: 그건 사장님 말이 아니라 모델이 사진을 보고
    적은 것이지만, **아무것도 없는 데서 지어낸 것과는 다르다.** 오탐을 만들지
    않는 쪽을 골랐다. 사진 메모 자체가 지어낸 것인지는 `vision` 쪽에서 볼 몫이다.
    """
    return [
        (category, term)
        for category, terms in CLAIM_TERMS.items()
        for term in terms
        if term in text and term not in grounds
    ]
